"""Find Mandragora spots the player can reach and freeze them as DrovaRandomizer/Data/AlrauneSpots.g.cs.

One-time data job against a running game (tests/scenarios/alraune_sweep.scn starts one and keeps it):
seeds are overworld pickups in the plants' kind of country, candidates sit a few hundred units
around each seed, and a candidate is kept when the game's own A* graph walks from the seed to it
(rando_reach). Pickups are reachable by design, so a kept candidate is too.

Run:  python tools/sweep_alraune_spots.py [port]
"""

import json
import math
import os
import socket
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "DrovaRandomizer", "Data", "AlrauneSpots.g.cs")
PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 47101

# Open overworld country only: no settlements, faction homes, caves, the Riverbed (Key Harald's door)
# or chunk-named wilds, most of which are interiors.
AREAS = {"Floodplain Forest", "Red Moor", "Forest Primeval", "Coniferous Forest", "Knoll in the Floodplain Forest",
         "Morbid Moor", "Heath", "Entrance to Nemeton"}
SEEDS_PER_AREA = 20
OFFSETS = ((320, 0), (0, 320), (-320, 0), (0, -320))
MIN_SPACING = 200


def ask(command):
    with socket.create_connection(("127.0.0.1", PORT), timeout=120) as s:
        f = s.makefile("rw", encoding="utf-8", newline="\n")
        f.write(command + "\n")
        f.flush()
        answer = f.readline().rstrip()
    if not answer.startswith("ok"):
        raise RuntimeError(command + " -> " + answer)
    return answer[3:]


def is_overworld(x, y):
    # Interiors live in far map bands the overworld never reaches (see gen_teleporter_pairs.is_interior).
    return -12000 <= y <= 12000 and -20000 <= x <= 36000


def seeds():
    with open(os.path.join(REPO, "tools", "extracted", "world_locations.json"), encoding="utf-8") as fh:
        locations = json.load(fh)
    by_area = {}
    for name, rec in sorted(locations.items()):
        if rec["category"] == "Pickup" and rec["area"] in AREAS and is_overworld(rec["x"], rec["y"]):
            by_area.setdefault(rec["area"], []).append(rec)
    picked = []
    for area, recs in sorted(by_area.items()):
        step = max(1, len(recs) // SEEDS_PER_AREA)
        picked += recs[::step][:SEEDS_PER_AREA]
    return picked


def main():
    plants = sorted(entry.split("@")[0] for entry in ask("rando_alraunes").split(";") if entry)
    print("plants:", plants)
    spots = []
    todo = seeds()
    for i, seed in enumerate(todo):
        ask("tp %d,%d" % (seed["x"], seed["y"]))
        time.sleep(4)
        candidates = [(seed["x"] + dx, seed["y"] + dy) for dx, dy in OFFSETS]
        answers = ask("rando_reach " + ";".join("%d,%d" % c for c in candidates)).split(";")
        for (x, y), ok in zip(candidates, answers):
            if ok == "1" and all(math.hypot(x - sx, y - sy) >= MIN_SPACING for sx, sy, _ in spots):
                spots.append((x, y, seed["area"]))
        print("%d/%d %s: %s -> %d spots" % (i + 1, len(todo), seed["area"], "".join(answers), len(spots)))

    lines = [
        "// Generated by tools/sweep_alraune_spots.py from an in-game reachability sweep. Do not edit by hand.",
        "namespace DrovaRandomizer.Data",
        "{",
        "    public static class AlrauneSpots",
        "    {",
        "        /// <summary>GuidComponent guids of the Mandragora plants the game places.</summary>",
        "        public static readonly string[] Plants = { %s };" % ", ".join('"%s"' % p for p in plants),
        "",
        "        /// <summary>Spots the game's A* graph reaches from a pickup: x, y and area.</summary>",
        "        public static readonly (float X, float Y, string Area)[] Spots =",
        "        {",
    ]
    lines += ['            (%sf, %sf, "%s"),' % (x, y, area) for x, y, area in spots]
    lines += ["        };", "    }", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines))
    print("wrote %d spots for %d plants -> %s" % (len(spots), len(plants), OUT))


if __name__ == "__main__":
    main()
