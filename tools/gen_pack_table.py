"""Freeze the elite packs: DrovaRandomizer/Data/PackTable.g.cs.

For every creature LazyActor spawner (tools/extract_locations/npcs_raw.json), the nearest spawners of the same prefab
within RADIUS world units, at most MAX_NEIGHBOURS. A common creature next to an epic or legendary one becomes its
minion, see Affixes.RollWithPack.

Run:  python tools/gen_pack_table.py
"""

import json
import math
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NPCS = os.path.join(REPO, "tools", "extract_locations", "npcs_raw.json")
OUT_CS = os.path.join(REPO, "DrovaRandomizer", "Data", "PackTable.g.cs")
RADIUS = 400
MAX_NEIGHBOURS = 4


def main():
    spawners = [(guid, rec["x"], rec["y"], rec["prefab_guid"])
                for guid, rec in sorted(json.load(open(NPCS, encoding="utf-8")).items()) if not rec["is_npc"]]
    lines = [
        "// Generated by tools/gen_pack_table.py. Do not edit by hand.",
        "namespace DrovaRandomizer.Data",
        "{",
        "    public static class PackTable",
        "    {",
        "        /// <summary>Creature spawner guid to the nearest spawners of its prefab, nearest first.</summary>",
        "        public static readonly Dictionary<string, string[]> Neighbours = new(StringComparer.Ordinal)",
        "        {",
    ]
    for guid, x, y, prefab in spawners:
        near = sorted((math.hypot(ox - x, oy - y), other) for other, ox, oy, op in spawners
                      if other != guid and op == prefab and math.hypot(ox - x, oy - y) <= RADIUS)
        if near:
            names = ", ".join('"%s"' % other for _, other in near[:MAX_NEIGHBOURS])
            lines.append('            ["%s"] = [%s],' % (guid, names))
    lines += ["        };", "    }", "}", ""]
    with open(OUT_CS, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("%d spawners with a pack" % (len(lines) - 12))


if __name__ == "__main__":
    main()
