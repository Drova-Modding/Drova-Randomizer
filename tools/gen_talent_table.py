"""Freeze the teachable talents: DrovaRandomizer/Data/TalentTable.g.cs.

A talent is teachable when some TeacherConfig asset lists it (TeacherConfig._talents). The configs and
talent names are read from the AssetRipper export; talents are named by their asset name, which is
what the mod looks them up by at runtime (Modding API TalentContainerDatabase.TryGetTalent).

Run:  python tools/gen_talent_table.py
"""

import glob
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPORT = r"C:\Users\fpabs\Documents\Projekte\DrovaDecompiled\ExportedProject\Assets"
ASSETS = os.path.join(EXPORT, "MonoBehaviour")
OUT = os.path.join(REPO, "DrovaRandomizer", "Data", "TalentTable.g.cs")


def main():
    names = {}
    for meta in glob.glob(os.path.join(EXPORT, "**", "Talent*.asset.meta"), recursive=True):
        guid = re.search(r"guid: (\w+)", open(meta, encoding="utf-8").read()).group(1)
        asset = open(meta[:-5], encoding="utf-8", errors="replace").read()
        names[guid] = re.search(r"m_Name: (\S+)", asset).group(1)

    teachers = {}
    for path in glob.glob(os.path.join(ASSETS, "TeacherConfig_*.asset")):
        text = open(path, encoding="utf-8", errors="replace").read()
        teacher = re.search(r"m_Name: (\S+)", text).group(1)
        for guid in re.findall(r"_talent: \{fileID: \d+, guid: (\w+)", text):
            teachers.setdefault(teacher, set()).add(names[guid])

    teachable = sorted(set().union(*teachers.values()))
    lines = [
        "// Generated by tools/gen_talent_table.py. Do not edit by hand.",
        "namespace DrovaRandomizer.Data",
        "{",
        "    public static class TalentTable",
        "    {",
        "        /// <summary>Talent asset names some teacher teaches: %d talents from %d teachers.</summary>" % (len(teachable), len(teachers)),
        "        public static readonly string[] Teachable =",
        "        {",
    ]
    lines += ['            "%s",' % name for name in teachable]
    lines += ["        };", "    }", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines))
    print("%d teachable talents from %d teachers -> %s" % (len(teachable), len(teachers), OUT))


if __name__ == "__main__":
    main()
