"""Freeze the monster shuffle pool: DrovaRandomizer/Data/MonsterTable.g.cs + tools/extracted/monster_exclusions.json.

Every creature LazyActor spawner (tools/extract_locations/npcs_raw.json) is either in the pool, with its
prefab and health tier, or excluded with a reason. Excluded: anything a quest, dialogue or fight graph
names (by guid), scripted spawners (waves, quest, intro, expedition, Red Tower and other named setups),
critters and pets, and every prefab that is a boss, a one-off, water-bound or otherwise special. The
pool is a whitelist of ordinary roaming monsters, so a new prefab stays vanilla until someone adds it.

Inputs: npcs_raw.json, the creature prefab names from the Modding API's AddressableAccess.cs (addressable
guid -> prefab name), the AssetRipper export (prefab -> _maxHealth) and a string dump of every graph
(drova-moddev skill: dump_graph_strings.py ".*" all_graphs.txt).

Run:  python tools/gen_monster_table.py <all_graphs.txt>
"""

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NPCS = os.path.join(REPO, "tools", "extract_locations", "npcs_raw.json")
ADDRESSABLES = os.path.join(os.path.dirname(REPO), "Drova Modding API", "Drova Modding API", "Access", "AddressableAccess.cs")
PREFABS = r"C:\Users\fpabs\Documents\Projekte\DrovaDecompiled\ExportedProject\Assets\Objects\Prefabs\Actors"
OUT_CS = os.path.join(REPO, "DrovaRandomizer", "Data", "MonsterTable.g.cs")
OUT_EXCLUSIONS = os.path.join(REPO, "tools", "extracted", "monster_exclusions.json")

# Ordinary roaming monsters. Water-bound (WaterAmbusher, WaterDevil), burrowing (Worm), scripted
# (Foglet patches, Great Tusk minions, intro boars), bosses and one-offs are left out on purpose.
POOL_PREFABS = {
    "BabySnapper", "Bloodquito_Auwald", "Bloodquito_Rotmoor", "Bloodquito_Kamikaze", "WaterRat", "WaterRat_Bone",
    "Sprigga", "Sprigga_Yellow", "Sprigga_Young_Hidden", "Sprigga_Young_Normal", "Sprigga_Young_Yellow_Normal",
    "Ripper", "HungryRipper", "HungryRipper_InstantAggro", "ShadowRipper", "ShadowRipper_Ambush",
    "ShadowRipper_Ambush_LittleAggroRange", "Snapper", "Snapper_Weak", "Snapper_ExtraWeak", "Spitter", "Spitter_Weak",
    "Spitter_ExtraWeak", "DiggerPig", "Frog_Melee", "Frog_Ranged", "Stalker_Red", "Stalker_Blue", "Stalker_Green",
    "Harpy", "Boar", "Boar_Luminous", "Banshee", "Menshee", "MortarShroom", "StoneFist", "StoneFist_BigGroupAggro",
    "Draugr_Spear", "Draugr_Sword_Shield", "Draugr_Mage", "Draugr_Axe", "EnemyFlesh_Melee",
}

# Spawner name tokens of scripted setups, whatever prefab they carry.
SCRIPTED_TOKENS = ("Quest", "Expedition", "GreatTusk", "Intro", "Ritual", "HuntTheRippers", "Wave", "Letter",
                   "RedTower", "Henik", "BetterKeepMeSafe", "Friendly", "PaperChase", "LostShoe", "Secret", "Brutus",
                   "AtlanterBuff", "YouDoNotFitHere", "Honey", "Chapter4", "Cay", "TrainingDummy", "Critter", "Bandit")

# Health bands for "same tier": a spawner only trades with creatures of its own band.
TIER_LIMITS = (100, 400, 900, 1600)


def tier(health):
    return sum(1 for limit in TIER_LIMITS if health > limit)


def main():
    graphs = open(sys.argv[1], encoding="utf-8", errors="replace").read().lower()
    names = dict((guid, name) for name, guid in re.findall(
        r'AssetReferenceGameObject (\w+) = new\("([0-9a-f]{32})"\)', open(ADDRESSABLES, encoding="utf-8").read()))
    health = {}
    for root, _, files in os.walk(PREFABS):
        for f in files:
            if f.endswith(".prefab") and f[:-7] in POOL_PREFABS:
                m = re.search(r"_maxHealth: (\d+)", open(os.path.join(root, f), encoding="utf-8", errors="replace").read())
                health[f[:-7]] = int(m.group(1))
    missing = POOL_PREFABS - set(health)
    assert not missing, "no health for %s" % sorted(missing)

    pool, excluded = [], {}
    for guid, rec in sorted(json.load(open(NPCS, encoding="utf-8")).items()):
        if rec["is_npc"]:
            continue
        prefab = names.get(rec["prefab_guid"], "?")
        if guid.lower() in graphs or guid.replace("-", "").lower() in graphs:
            excluded[guid] = "named by a quest, dialogue or fight graph (%s)" % rec["name"]
        elif any(token.lower() in rec["name"].lower() for token in SCRIPTED_TOKENS):
            excluded[guid] = "scripted spawner %s" % rec["name"]
        elif prefab not in POOL_PREFABS:
            excluded[guid] = "prefab %s is not an ordinary roaming monster" % prefab
        else:
            pool.append((guid, rec["prefab_guid"], tier(health[prefab]), prefab))

    lines = [
        "// Generated by tools/gen_monster_table.py. Do not edit by hand.",
        "namespace DrovaRandomizer.Data",
        "{",
        "    public static class MonsterTable",
        "    {",
        "        /// <summary>Shuffleable creature spawners: LazyActor guid, prefab addressable guid, health tier.</summary>",
        "        public static readonly (string Guid, string Prefab, int Tier)[] Spawners =",
        "        {",
    ]
    lines += ['            ("%s", "%s", %d),' % (g, p, t) for g, p, t, _ in pool]
    lines += ["        };", "    }", "}", ""]
    with open(OUT_CS, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines))
    with open(OUT_EXCLUSIONS, "w", encoding="utf-8") as fh:
        json.dump(excluded, fh, indent=1, sort_keys=True, ensure_ascii=True)
    reasons = {}
    for reason in excluded.values():
        key = reason.split(" ")[0]
        reasons[key] = reasons.get(key, 0) + 1
    print("pool %d spawners, excluded %d %s" % (len(pool), len(excluded), reasons))


if __name__ == "__main__":
    main()
