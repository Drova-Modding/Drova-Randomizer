using UnityEngine;

namespace DrovaRandomizer.Data
{
    /// <summary>
    /// Overlay geometry for one riddle plate or clue stone. Region coordinates are sprite-rect pixels
    /// from the bottom left. The alpha mask, row-major bottom-up, makes overlays follow broken plate edges.
    /// </summary>
    public readonly struct RuneHintPiece
    {
        public readonly string Pattern;
        /// <summary>"full" for an 8x8 plate, or the pattern quadrant a 4x4 clue displays.</summary>
        public readonly string Quad;
        public readonly int Cells;
        public readonly float CellSize;
        public readonly int X;
        public readonly int Y;
        public readonly int W;
        public readonly int H;
        /// <summary>Image-space to sprite-rect-space correction, since the atlas trims the plate art.</summary>
        public readonly float OffsetX;
        public readonly float OffsetY;
        public readonly Color32 OnColor;
        public readonly Color32 OffColor;
        private readonly string _maskHex;

        public RuneHintPiece(string pattern, string quad, int cells, float cellSize,
            int x, int y, int w, int h, float offsetX, float offsetY,
            Color32 onColor, Color32 offColor, string maskHex)
        {
            Pattern = pattern;
            Quad = quad;
            Cells = cells;
            CellSize = cellSize;
            X = x;
            Y = y;
            W = w;
            H = h;
            OffsetX = offsetX;
            OffsetY = offsetY;
            OnColor = onColor;
            OffColor = offColor;
            _maskHex = maskHex;
        }

        /// <summary>Is the mask opaque at region-local (x, y bottom-up)?</summary>
        public bool MaskAt(int x, int y)
        {
            int index = y * W + x;
            char c = _maskHex[index / 4];
            int nibble = c <= '9' ? c - '0' : char.ToLowerInvariant(c) - 'a' + 10;
            return (nibble & (1 << (3 - index % 4))) != 0;
        }
    }

    /// <summary>Hint-art sprite name -> overlay geometry, generated by tools/extract_locations/gen_rune_hint_table.py.</summary>
    public static partial class RuneHintTable;
}
