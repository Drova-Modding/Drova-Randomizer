namespace DrovaRandomizer.Data
{
    /// <summary>How a reward reaches the player.</summary>
    public enum GrantKind
    {
        Item,
        Xp,
        LearningPoint,
        Attribute,
        MaxHealth,
        Talent
    }

    /// <summary>Fill priority. Progression gates locations, useful is real character power, filler is the rest.</summary>
    public enum Tier
    {
        Progression,
        Useful,
        Filler
    }

    /// <summary>
    /// One grantable reward. <see cref="Id"/> is the game's readable id for <see cref="GrantKind.Item"/>
    /// the attribute name ("strength", "dexterity", "mind") for <see cref="GrantKind.Attribute"/> and the
    /// talent asset name for <see cref="GrantKind.Talent"/>.
    /// <see cref="WorldCount"/> is how often vanilla hands the item out, the weight of the bulk loot draw.
    /// <see cref="SupplyGroup"/> is non-empty for ordinary items a quest consumes, which the pool keeps a stock of.
    /// </summary>
    public sealed record ItemDef(string Id, string Name, GrantKind Kind, int Amount, Tier Tier, int Sell, int Buy,
        float WorldCount, bool Extended, bool CookedFood, string SupplyGroup)
    {
        /// <summary>True when a shop can sell it: the trade window only lists items with a buy and a sell price.</summary>
        public bool Sellable => Kind == GrantKind.Item && Buy > 0 && Sell > 0;
    }

    /// <summary>Every reward the randomizer can place. Rows live in ItemTable.g.cs, generated by tools/gen_data.py.</summary>
    public static partial class ItemTable
    {
        private static Dictionary<string, ItemDef>? _byId;

        /// <summary>One reward per teachable talent, only placed when the run puts talents into the pool.</summary>
        public static readonly ItemDef[] Talents =
        [
            .. TalentTable.Teachable
                .Select(name => new ItemDef(name, name.Replace('_', ' '), GrantKind.Talent, 1, Tier.Useful, 0, 0, 0f, false, false, "")),
        ];

        /// <summary>The reward with this id, or null.</summary>
        public static ItemDef? Get(string? id)
        {
            _byId ??= All.Concat(Talents).ToDictionary(item => item.Id, StringComparer.Ordinal);
            return id != null && _byId.TryGetValue(id, out ItemDef? found) ? found : null;
        }
    }
}
